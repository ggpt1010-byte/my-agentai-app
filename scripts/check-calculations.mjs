import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
fs.mkdirSync('.check',{recursive:true});
const out='.check/planner-check.mjs';
fs.writeFileSync(out,ts.transpileModule(fs.readFileSync('src/apps/ucsb/planner.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
const {defaultState,flightCost,allocation,spent,stateSchema,normalizeState,homeCoverage,homeCost,securedStay}=await import('../'+out+'?t='+Date.now());
const s=structuredClone(defaultState);
assert.equal(allocation(s),26000000);
assert.equal(Math.max(s.settings.total,allocation(s),spent(s))-s.settings.support,16000000);
const f={id:'test',name:'검증',airport:'LAX',currency:'KRW',fare:1200000,extra:200000,extraForBags:2,outBags:1,inBags:1,hours:12,stops:0,url:'',note:'',history:[]};
assert.equal(flightCost(s,f).total,null,'Unknown ground cost must not rank as zero');
s.transports[0].cost=100;
assert.equal(flightCost(s,f).total,1540000,'1.2M airfare + 200k bags + $100*1400 transport');
assert.equal(flightCost(s,{...f,extra:null}).total,null,'Unknown required baggage must not rank');
assert.equal(flightCost(s,{...f,outBags:2,inBags:2,extra:null}).total,1340000,'Included bags must not add an extra fee');
assert.equal(flightCost(s,{...f,currency:'USD',fare:1000,extra:100}).total,1680000);
s.settings.bags=1;
assert.equal(flightCost(s,f).total,1340000,'One included bag satisfies one-bag comparison');
assert.equal(flightCost(s,{...f,outBags:0,inBags:0}).total,null,'Two-bag quote must not be reused for one-bag purchase');
s.expenses=[{id:'x',name:'숙소',category:'housing',amount:100,currency:'USD',date:'2027-02-09',note:''}];
assert.equal(spent(s),140000);
s.settings.rate=1500;
assert.equal(spent(s),150000);
assert.equal(stateSchema.safeParse(s).success,true);
assert.equal(stateSchema.safeParse({...s,settings:{...s.settings,ret:'2026-01-01'}}).success,false);
assert.equal(stateSchema.safeParse({...s,settings:{...s.settings,rate:0}}).success,false);
// 집 후보: 하위 호환, 체류 커버, 비용, 계약 확보 기간
const legacy=structuredClone(defaultState);delete legacy.homes;
assert.deepEqual(normalizeState(legacy).homes,[],'Saved data from before homes existed must load with an empty list');
assert.equal(stateSchema.safeParse(legacy).success,true,'Legacy payload must still pass PUT validation');
const h={id:'h',name:'IV',area:'Isla Vista',room:'1인실',url:'',currency:'USD',rent:1000,upfront:null,from:'2027-02-01',to:'2027-06-14',furnished:false,utilities:false,status:'idea',note:''};
const hs={...structuredClone(defaultState),homes:[h]};
const cov=homeCoverage(hs,h);
assert.equal(cov.days,125,'2/9..6/14 overlaps 125 days');
assert.equal(cov.before,0);assert.equal(cov.after,55,'6/14..8/8 leaves 55 days uncovered');
assert.equal(homeCoverage(hs,{...h,from:''}),null,'Missing dates give no coverage');
const hc=homeCost(hs,h);
assert.equal(hc.monthly,1400000,'$1,000 at planning rate 1,400');
assert.equal(hc.overBudget,-600000,'Housing budget 2,000,000 per month');
assert.equal(hc.upfront,null,'Unknown deposit stays unknown');
assert.equal(homeCost(hs,{...h,rent:null}).stay,null,'Unknown rent must not count as zero');
assert.equal(stateSchema.safeParse({...hs,homes:[{...h,to:'2027-01-01'}]}).success,false,'End before start is rejected');
const signed={...hs,homes:[{...h,status:'signed'},{...h,id:'h2',from:'2027-06-01',to:'2027-08-31',status:'signed'},{...h,id:'h3',from:'2027-01-01',to:'2027-12-31',status:'idea'}]};
assert.equal(securedStay(signed).days,180,'Overlapping signed contracts count once and clip to the stay');
console.log('12 budget, currency, baggage, incomplete-cost and date validation checks passed.');
console.log('12 housing shortlist compatibility, coverage and cost checks passed.');
